#!/usr/bin/env bash
# Collect libmpv and its non-system dependency closure into <out_dir> for bundling (PLAN §4.10).
# Usage: tools/mpv/linux.sh <out_dir>
# Called by build-linux.sh inside the pinned container (LIBMPV_SRC = the freshly built libmpv).
# Env: LIBMPV_SRC overrides the libmpv path.
set -euo pipefail

OUT="${1:?usage: $0 <out_dir>}"
HERE="$(cd "$(dirname "$0")" && pwd)"
# shellcheck disable=SC1091
. "$HERE/pins.env"

SRC="${LIBMPV_SRC:-}"
if [ -z "$SRC" ]; then
  for c in /usr/lib/x86_64-linux-gnu/libmpv.so.2 /usr/lib/libmpv.so.2 /usr/lib64/libmpv.so.2; do
    [ -e "$c" ] && SRC="$c" && break
  done
fi
[ -n "$SRC" ] && [ -e "$SRC" ] || { echo "libmpv.so.2 not found (install libmpv2 or set LIBMPV_SRC)" >&2; exit 1; }
SRC="$(readlink -f "$SRC")"

# Libraries that must come from the user's system: glibc, GPU/windowing/audio stacks and anything
# tied to host daemons or driver ABIs. Everything else is bundled.
EXCLUDE='^(linux-vdso|ld-linux|libc\.so|libm\.so|libdl\.so|libpthread\.so|librt\.so|libresolv|libnsl|libutil|libanl|libgcc_s|libstdc\+\+|libGL\.|libGLX|libGLdispatch|libEGL|libOpenGL|libGLESv|libgbm|libdrm|libX11|libX11-xcb|libXext|libXrandr|libXrender|libXfixes|libXi\.|libXcursor|libXinerama|libXss|libXv\.|libXxf86vm|libxcb|libXau|libXdmcp|libwayland|libxkbcommon|libvulkan|libva|libvdpau|libasound|libpulse|libpipewire|libjack|libsndio|libsystemd|libdbus|libudev|libfontconfig|libfreetype|libz\.so|libffi)'

mkdir -p "$OUT"
OUT="$(cd "$OUT" && pwd)"
cp -L "$SRC" "$OUT/libmpv.so.2"

missing=0
while read -r name path; do
  [ -n "$path" ] || continue
  if echo "$name" | grep -Eq "$EXCLUDE"; then continue; fi
  cp -L "$path" "$OUT/$name" 2>/dev/null || cp -L "$path" "$OUT/$(basename "$path")"
done < <(ldd "$SRC" | awk '/=> \//{print $1, $3}')
if ldd "$SRC" | grep -q 'not found'; then
  echo "unresolved dependencies:" >&2; ldd "$SRC" | grep 'not found' >&2; missing=1
fi

if command -v patchelf >/dev/null 2>&1; then
  # shellcheck disable=SC2016 # literal $ORIGIN is the point
  for f in "$OUT"/*.so*; do patchelf --set-rpath '$ORIGIN' "$f"; done
else
  echo "warning: patchelf not found; rpath not set (install patchelf in the release container)" >&2
fi

# Manifest: what was bundled, from which package, with hashes (feeds PINNED.md and the SBOM).
{
  echo "# libmpv bundle, generated by tools/mpv/linux.sh on $(date -u +%FT%TZ)"
  echo "source: $SRC"
  echo "mpv ${MPV_VERSION}, libplacebo ${LIBPLACEBO_VERSION} (${LIBPLACEBO_COMMIT}), image ${MPV_LINUX_IMAGE}"
  if command -v dpkg-query >/dev/null 2>&1; then
    echo "ffmpeg (libavcodec-dev): $(dpkg-query -W -f='${Version}' libavcodec-dev 2>/dev/null || echo unknown)"
  fi
  (cd "$OUT" && sha256sum ./*.so* | sort -k2)
} > "$OUT/MANIFEST.txt"

echo "staged $(find "$OUT" -name '*.so*' | wc -l) libraries in $OUT"
exit "$missing"
